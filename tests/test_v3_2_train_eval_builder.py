"""The v3.2 train/eval notebook must have a builder, and the builder must win.

For most of its life ``notebooks/spancall_lean_v3_2_train_eval.ipynb`` was edited
as raw notebook JSON: fixes landed as unreviewable blob diffs, and a later edit
could silently contradict an earlier one (that is how the latency metric drifted
for several versions). Every other notebook in this repository is generated by
``scripts/build_*.py`` so that the cell text is reviewable Python.

``scripts/build_lean_v3_2_train_eval_notebook.py`` closes that gap. These tests
lock the contract:

1. the builder exists and does not need the network or a GPU,
2. ``--check`` reports fresh vs. stale correctly (it must fail on drift, not
   merely pass because nothing is compared),
3. a rebuild is a no-op for cell text, cell ids, notebook metadata **and executed
   outputs** — this notebook is the record of the run the paper quotes, so a
   rebuild that quietly dropped 19 executed code cells would destroy the evidence.

Tests skip when the generated notebook is absent, matching the convention in
``tests/test_notebook_v3_fixes.py``.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any, Dict, List

import pytest

ROOT = Path(__file__).resolve().parents[1]
BUILDER = ROOT / "scripts" / "build_lean_v3_2_train_eval_notebook.py"
NOTEBOOK = ROOT / "notebooks" / "spancall_lean_v3_2_train_eval.ipynb"

_skip_no_builder = pytest.mark.skipif(
    not BUILDER.is_file(), reason="v3.2 train/eval builder missing"
)
_skip_no_notebook = pytest.mark.skipif(
    not NOTEBOOK.is_file(),
    reason=f"{NOTEBOOK.name} not built; run scripts/build_lean_v3_2_train_eval_notebook.py",
)


def _load_builder() -> Any:
    """Import the builder module without running ``__main__``."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("_build_v3_2", BUILDER)
    assert spec and spec.loader, f"cannot load {BUILDER}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _cell_fingerprint(path: Path) -> List[Dict[str, Any]]:
    """What a rebuild must preserve, per cell, independent of JSON formatting."""
    nb = json.loads(path.read_text(encoding="utf-8"))
    out: List[Dict[str, Any]] = []
    for cell in nb["cells"]:
        out.append(
            {
                "cell_type": cell["cell_type"],
                "source": "".join(cell["source"]).rstrip("\n"),
                "id": cell.get("id"),
                "execution_count": cell.get("execution_count"),
                "outputs": cell.get("outputs") or [],
            }
        )
    return out


@_skip_no_builder
def test_builder_exists_and_parses() -> None:
    """The source of truth for the v3.2 notebook is checked in as Python."""
    import ast

    tree = ast.parse(BUILDER.read_text(encoding="utf-8"))
    names = {n.name for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)}
    assert "build" in names, "builder has no build() entry point"

    # ``CELLS`` is annotated (``CELLS: List[Tuple[str, str]] = [...]``), so it is
    # an AnnAssign, not an Assign — check both or the assertion is vacuous.
    assigned = {
        target.id
        for node in ast.walk(tree)
        if isinstance(node, (ast.Assign, ast.AnnAssign))
        for target in (
            node.targets if isinstance(node, ast.Assign) else [node.target]
        )
        if isinstance(target, ast.Name)
    }
    assert "CELLS" in assigned, "builder must declare CELLS so the notebook text is readable"


@_skip_no_builder
@_skip_no_notebook
def test_builder_check_passes_on_a_fresh_notebook() -> None:
    """``--check`` against the committed artifact must exit 0."""
    module = _load_builder()
    module.build(check=True)  # raises SystemExit if stale


@_skip_no_builder
@_skip_no_notebook
def test_builder_check_fails_when_the_notebook_drifts(tmp_path: Path) -> None:
    """A cell edited outside the builder must be reported, not tolerated."""
    scratch = tmp_path / "scripts"
    scratch.mkdir()
    shutil.copy2(BUILDER, scratch / BUILDER.name)
    nb_dir = tmp_path / "notebooks"
    nb_dir.mkdir()
    target = nb_dir / NOTEBOOK.name

    drifted = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    for cell in drifted["cells"]:
        if cell["cell_type"] == "code":
            cell["source"] = ["# edited outside the builder\n"] + cell["source"]
            break
    target.write_text(json.dumps(drifted), encoding="utf-8")

    module = _load_builder()
    with pytest.raises(SystemExit) as exc:
        module.build(out_path=target, check=True)
    assert "stale" in str(exc.value), "drift must be reported as stale, not swallowed"


@_skip_no_builder
@_skip_no_notebook
def test_rebuild_is_lossless(tmp_path: Path) -> None:
    """A rebuild must reproduce the executed artifact exactly.

    This notebook carries the GPU run behind the reported numbers. If a rebuild
    dropped ``outputs``/``execution_count`` (the obvious naive builder bug) the
    evidence would be gone with no diff to notice, so it is asserted here.
    """
    target = tmp_path / NOTEBOOK.name
    shutil.copy2(NOTEBOOK, target)
    before = _cell_fingerprint(target)

    module = _load_builder()
    module.build(out_path=target)
    after = _cell_fingerprint(target)

    assert after == before, "rebuild changed cell text, ids, metadata or executed outputs"
    assert any(c["outputs"] for c in after), "rebuilt notebook lost all executed outputs"